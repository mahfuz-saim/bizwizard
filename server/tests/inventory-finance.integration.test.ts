import assert from 'node:assert/strict';
import { test } from 'node:test';
import { randomUUID } from 'node:crypto';
import express, { NextFunction, Request, Response } from 'express';
import jwt from 'jsonwebtoken';
import prisma from '../src/shared/prisma';
import config from '../src/config';
import { productService } from '../src/app/modules/product/product.service';
import { cashflowService } from '../src/app/modules/finance/cashflow/cashflow.service';
import { cashflowRoutes } from '../src/app/modules/finance/cashflow/cashflow.routes';
import { productRoutes } from '../src/app/modules/product/product.routes';
import type { IProduct } from '../src/app/modules/product/product.interface';

test('inventory and alert fixes against an isolated PostgreSQL database', { skip: process.env.INVENTORY_TEST_DATABASE !== '1' }, async t => {
    const url = new URL(process.env.DATABASE_URL!);
    assert.equal(url.hostname, '127.0.0.1');
    assert.equal(url.pathname, '/simulator_test');
    t.after(() => prisma.$disconnect());
    const user = await prisma.user.create({ data: { number: randomUUID(), name: 'Fixture owner', role: ['OWNER'], status: 'ACTIVE', OTP: 0 } });
    await prisma.owner.create({ data: { userID: user.id, name: 'Fixture owner', number: user.number, email: `${randomUUID()}@example.invalid`, dob: '1990-01-01', address: 'Fixture' } });
    const tenant = await prisma.tenant.create({ data: { name: 'Inventory fixture', ownerID: user.id } });
    const shop = await prisma.shop.create({ data: { shopName: 'Fixture shop', tenantID: tenant.id, ownerID: user.id, contact: 'Fixture' } });
    const supplierUser = await prisma.user.create({ data: { number: randomUUID(), role: ['SUPPLIER'], OTP: 0 } });
    await prisma.supplier.create({ data: { userID: supplierUser.id, number: supplierUser.number, name: 'Fixture supplier', company: 'Fixture' } });
    const supply = await prisma.shopSupplier.create({ data: { supplierId: supplierUser.id, shopId: shop.id, tenantID: tenant.id, number: supplierUser.number } });
    const initial: IProduct = { shopID: shop.id, name: 'Soap', category: 'PERSONAL_CARE_PRODUCTS', measuringUnit: 'Piece (pc)', lowStock: 0,
        lot: { stock: 10, buyPrice: 50, sellPrice: 60, mrp: 60, retail: 60, isMRPDefault: true, includeVAT: true, expDate: new Date('2027-01-05') } };
    const created = await productService.addProductInShop(initial, tenant.id);
    assert.equal(created.lowStock, 0);
    await prisma.shopConfig.create({ data: { shopID: shop.id, tenantID: tenant.id, defaultLowStockThreshold: 9 } });
    const originalCatalogCount = await prisma.inventory.count();
    // Mimic the old frontend: only variantId, no productID/name/unit.
    const restock = { shopID: shop.id, variantId: created.id, category: initial.category, supplierId: supplierUser.id,
        lot: { ...initial.lot, stock: 2, buyPrice: 53.35 } } as IProduct;
    const result = await productService.addPurchase([restock], tenant.id);
    assert.equal(result[0].id, created.id);
    assert.equal(result[0].lowStock, 0, 'restocking preserves the variant threshold');
    assert.equal(result[0].Lot.length, 1);
    assert.equal(result[0].Lot[0].stock, 2);
    assert.equal(result[0].Lot[0].supplyId, supply.id);
    assert.equal(await prisma.inventory.count(), originalCatalogCount);
    assert.equal((await prisma.shopVariant.findUniqueOrThrow({ where: { id: created.id } })).totalProducts, 12);
    const expense = await prisma.expenseItem.findFirstOrThrow({ where: { lotId: result[0].Lot[0].id } });
    assert.equal(expense.quantity, 2);
    assert.equal(expense.unitPrice, 53.35);
    assert.equal(expense.amount, 106.7);
    const lotsBefore = await prisma.lot.count();
    const expensesBefore = await prisma.expenseItem.count();
    await assert.rejects(productService.addPurchase([restock, { ...restock, variantId: randomUUID() }], tenant.id), /Product variant not found/);
    assert.equal(await prisma.lot.count(), lotsBefore, 'failed second line rolls back the first');
    assert.equal(await prisma.expenseItem.count(), expensesBefore);
    assert.equal((await prisma.shopVariant.findUniqueOrThrow({ where: { id: created.id } })).totalProducts, 12);
    await productService.updateProductInShop(created.id, { sellPrice: 65, expDate: null, name: 'Updated soap' }, tenant.id);
    const lots = await prisma.lot.findMany({ where: { shopVariantId: created.id } });
    assert(lots.every(lot => lot.expDate === null && lot.sellPrice === 65));
    await productService.updateProductInShop(created.id, { expDate: '2027-02-01' as unknown as Date }, tenant.id);
    assert((await prisma.lot.findMany({ where: { shopVariantId: created.id } })).every(lot => lot.expDate?.toISOString().startsWith('2027-02-01')));
    await assert.rejects(productService.updateProductInShop(created.id, { name: 'Must roll back', expDate: 'invalid-date' as unknown as Date }, tenant.id));
    assert.equal((await prisma.shopVariant.findUniqueOrThrow({ where: { id: created.id } })).name, 'Updated soap');

    const alert = await prisma.cashAlert.create({ data: { tenantID: tenant.id, shopID: shop.id, alertType: 'BUFFER_BELOW_TARGET', severity: 'WARNING', title: 'Buffer low', message: 'Fixture', triggerRule: 'fixture', metricSnapshot: {}, recommendedActions: [{ actionType: 'COLLECT_DEBT', description: 'Review overdue receivables', projectedImpact: 100 }] } });
    const cashBefore = await prisma.cashTransaction.count();
    const proposals = await Promise.all([0, 1].map(() => cashflowService.executeAlertAction(tenant.id, shop.id, alert.id, { actionIndex: 0 })));
    assert.equal(proposals[0].id, proposals[1].id, 'repeated clicks create one proposal');
    assert.equal(proposals[0].status, 'PROPOSED');
    assert.equal(proposals[0].amount, 0, 'recommendation impact is not a transaction amount');
    assert.equal((await prisma.cashAlert.findUniqueOrThrow({ where: { id: alert.id } })).status, 'OPEN');
    const approved = await cashflowService.decideTreasuryAction(tenant.id, shop.id, proposals[0].id, true);
    assert.equal(approved.status, 'APPROVED');
    assert.equal(approved.executedAt, null);
    assert.equal(await prisma.cashTransaction.count(), cashBefore);
    await assert.rejects(cashflowService.decideTreasuryAction(tenant.id, shop.id, approved.id, true), /Only proposed/);
    await assert.rejects(cashflowService.executeAlertAction(tenant.id, shop.id, alert.id, { actionIndex: 99 }), /available alert/);
    await cashflowService.ackAlert(tenant.id, shop.id, alert.id, { action: 'dismiss' });
    assert(!(await cashflowService.listAlerts(tenant.id, shop.id, 'OPEN')).some(a => a.id === alert.id));

    config.jwt.secret = 'local-integration-test-only';
    const app = express(); app.use(express.json()); app.use('/product', productRoutes); app.use('/cashflow', cashflowRoutes);
    app.use((error: Error & { statusCode?: number }, _req: Request, res: Response, _next: NextFunction) => res.status(error.statusCode ?? 400).json({ message: error.message }));
    const server = app.listen(0, '127.0.0.1');
    await new Promise<void>(resolve => server.once('listening', resolve));
    t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
    const port = (server.address() as { port: number }).port;
    const post = (path: string, body: unknown, role = 'OWNER') => fetch(`http://127.0.0.1:${port}${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${jwt.sign({ userID: user.id, role }, config.jwt.secret!)}`, 'x-tenant-id': tenant.id }, body: JSON.stringify(body) });
    assert.equal((await post(`/cashflow/alerts/${alert.id}/execute?shopId=${shop.id}`, { actionIndex: 0 }, 'EMPLOYEE')).status, 403);
    assert.equal((await post(`/cashflow/treasury-actions/${approved.id}/approve?shopId=${shop.id}`, {}, 'EMPLOYEE')).status, 403);
    assert.equal((await post(`/cashflow/alerts/${alert.id}/execute?shopId=${shop.id}`, { actionIndex: 0, projectedImpact: 99999 })).status, 400);
    const httpPurchase = await post('/product/purchase', { lines: [restock, restock] });
    assert.equal(httpPurchase.status, 201, await httpPurchase.text());
    assert.equal((await prisma.shopVariant.findUniqueOrThrow({ where: { id: created.id } })).totalProducts, 16);
});
