import assert from 'node:assert/strict';
import { test } from 'node:test';
import { randomUUID } from 'node:crypto';
import express, { NextFunction, Request, Response } from 'express';
import jwt from 'jsonwebtoken';
import prisma from '../src/shared/prisma';
import config from '../src/config';
import { matchedEvaluationService } from '../src/app/modules/finance/agents/matchedEvaluation.service';
import { replayFallback, replayChoiceSchema, runMatchedReplay, replayHash } from '../src/app/modules/finance/agents/matchedReplay';
import { ensureCatalog } from '../src/app/modules/finance/shared/catalog';
import { agentsService } from '../src/app/modules/finance/agents/agents.service';
import { agentsRoutes } from '../src/app/modules/finance/agents/agents.routes';
import { hashInput, setAiBudgetGate } from '../src/lib/ai/client';
import { saveEvidence } from '../scripts/evidence-output';

test('shop-specific matched replay: frozen data, paired outcomes, scopes, idempotency and export', {skip:process.env.MATCHED_EVALUATION_TEST_DATABASE!=='1'},async t=>{
  const url=new URL(process.env.DATABASE_URL!);assert.equal(url.hostname,'127.0.0.1');assert.equal(url.pathname,'/simulator_test');
  process.env.OPENAI_API_KEY='';
  t.after(async()=>{setAiBudgetGate(null);delete process.env.OPENAI_API_KEY;await prisma.$disconnect();});
  const user=await prisma.user.create({data:{number:randomUUID(),role:['OWNER'],OTP:0}});
  await prisma.owner.create({data:{userID:user.id,number:user.number,name:'Synthetic evaluator',email:`${randomUUID()}@example.invalid`,dob:'1990-01-01',address:'Synthetic'}});
  const tenant=await prisma.tenant.create({data:{name:'Matched fixture',ownerID:user.id}});
  const shop=await prisma.shop.create({data:{tenantID:tenant.id,ownerID:user.id,shopName:'Matched fixture',contact:'Synthetic'}});
  const scope={tenantID:tenant.id,shopID:shop.id};
  const variant=await prisma.shopVariant.create({data:{...scope,name:'Synthetic stock',totalProducts:100}});
  const lot=await prisma.lot.create({data:{tenantID:tenant.id,shopVariantId:variant.id,stock:100,buyPrice:5000,sellPrice:10000,mrp:10000,retail:10000,isMRPDefault:true,includeVAT:false}});
  const sales=Array.from({length:120},(_,i)=>({id:randomUUID(),...scope,totalPrice:10000,totalQuantity:1,status:'PAID' as const,createdAt:new Date(Date.now()-(i+1)*86400000)}));
  await prisma.checkout.createMany({data:sales});
  await prisma.checkoutItem.createMany({data:sales.map(s=>({tenantID:tenant.id,checkoutID:s.id,lotId:lot.id,variantId:variant.id,productName:'Synthetic stock',quantity:1,unitPrice:10000,discountedPrice:10000,createdAt:s.createdAt}))});
  await prisma.cashCommitment.create({data:{...scope,name:'Synthetic rent',amount:10000,dueDate:new Date(Date.now()+5*86400000),confidence:1,category:'RENT'}});
  await ensureCatalog(prisma as never);
  const product=await prisma.financeProduct.findFirstOrThrow({where:{minTenorMonths:{lte:6},maxTenorMonths:{gte:12}}});
  for (const months of [6,12]) await prisma.financingOffer.create({data:{...scope,financeProductID:product.id,providerID:product.providerID,offeredAmount:10000,offeredRate:product.interestRateMin,tenorMonths:months,advanceRate:0.5,effectiveApr:12,totalRepayment:11000,collateralRequired:false,collateralTypes:[],conditions:[],rationale:'Synthetic recorded quote',status:'ISSUED',confidence:1,aiModel:'fixture',promptVersion:'fixture',expiresAt:new Date(Date.now()+86400000)}});
  const source=async()=>({sales:await prisma.checkout.count({where:scope}),cash:await prisma.cashTransaction.findMany({where:scope,orderBy:{id:'asc'}}),stock:await prisma.lot.findUnique({where:{id:lot.id}})});
  const before=await source();
  const evaluation=await matchedEvaluationService.run(tenant.id,shop.id);
  assert.equal(evaluation.status,'COMPLETE');assert.equal(evaluation.usedFallback,true);
  assert.equal(evaluation.outcome.scorecards.length,4);
  assert(evaluation.outcome.scorecards.every((s:{status:string})=>s.status==='COMPLETE'));
  assert.deepEqual(await source(),before,'evaluation must not execute financial transactions or change inventory');
  assert.deepEqual(JSON.parse(JSON.stringify(runMatchedReplay(evaluation.snapshot,evaluation.choices,evaluation.seed))),evaluation.outcome);
  assert(evaluation.choicesFrozenAt<=evaluation.completedAt);
  assert.equal((await matchedEvaluationService.run(tenant.id,shop.id)).id,evaluation.id,'unchanged daily snapshots reuse frozen choices and outcomes');
  assert.equal(await prisma.financeEvaluation.count({where:scope}),1);
  assert.equal((await matchedEvaluationService.list(tenant.id,shop.id))[0].id,evaluation.id);
  await assert.rejects(matchedEvaluationService.get('foreign-tenant',shop.id,evaluation.id));
  const other=await prisma.shop.create({data:{tenantID:tenant.id,ownerID:user.id,shopName:'Empty other shop',contact:'Synthetic'}});
  await assert.rejects(matchedEvaluationService.get(tenant.id,other.id,evaluation.id),/not found/);
  await assert.rejects(matchedEvaluationService.run(tenant.id,other.id),/completeness/);
  const oldSnapshot=hashInput(evaluation.snapshot);
  const policies=await agentsService.listPolicies(tenant.id,shop.id);
  const analyst=policies.find((p:{agentType:string})=>p.agentType==='ANALYST_AGENT');
  await agentsService.updatePolicy(tenant.id,shop.id,analyst.id,{riskAppetite:0.7});
  process.env.OPENAI_API_KEY='synthetic-key-never-sent';
  setAiBudgetGate(async()=>({settle:async()=>{}}));
  let providerCalls=0;
  const fakeFetch=(async(_url:unknown,init?:RequestInit)=>{
    providerCalls++;
    const payload=JSON.parse(String(init?.body));
    const input=JSON.parse(payload.messages[1].content);
    assert.equal('seed' in input,false,'model must not see outcome seeds');
    assert.equal('paths' in input,false,'model must not see future outcome draws');
    const choice=replayFallback(input);
    assert(replayChoiceSchema(input).safeParse(choice).success);
    return new globalThis.Response(JSON.stringify({choices:[{message:{content:JSON.stringify(choice)}}],usage:{prompt_tokens:200,completion_tokens:100}}),{status:200,headers:{'Content-Type':'application/json'}});
  }) as typeof fetch;
  const concurrent=await Promise.allSettled([matchedEvaluationService.run(tenant.id,shop.id,fakeFetch),matchedEvaluationService.run(tenant.id,shop.id,fakeFetch)]);
  assert(concurrent.some(r=>r.status==='fulfilled'));
  assert.equal(await prisma.financeEvaluation.count({where:scope}),2);
  assert.equal(providerCalls,1,'concurrent requests must not duplicate paid model calls');
  assert.equal(hashInput((await matchedEvaluationService.get(tenant.id,shop.id,evaluation.id)).snapshot),oldSnapshot,'new mandates must not rewrite old evaluations');
  assert.deepEqual(await source(),before);
  process.env.OPENAI_API_KEY='';
  const app=express();app.use(express.json());app.use('/agents',agentsRoutes);
  app.use((error:{statusCode?:number;message:string},_req:Request,res:Response,_next:NextFunction)=>res.status(error.statusCode??400).json({message:error.message}));
  const server=app.listen(0,'127.0.0.1');await new Promise<void>(resolve=>server.once('listening',resolve));t.after(()=>new Promise<void>(resolve=>server.close(()=>resolve())));
  const base=`http://127.0.0.1:${(server.address() as {port:number}).port}/agents`;
  const headers=(role:string)=>({'Content-Type':'application/json',Authorization:`Bearer ${jwt.sign({userID:user.id,role},config.jwt.secret!)}`,'x-tenant-id':tenant.id});
  assert.equal((await fetch(`${base}/evaluations?shopId=${shop.id}`,{method:'POST',headers:headers('EMPLOYEE'),body:'{}'})).status,403);
  assert.equal((await fetch(`${base}/evaluations?shopId=${shop.id}`,{method:'POST',headers:headers('OWNER'),body:JSON.stringify({seed:1,alpha:999})})).status,400);
  assert.equal((await fetch(`${base}/evaluations/${evaluation.id}?shopId=${other.id}`,{headers:headers('OWNER')})).status,404);
  const exported=await fetch(`${base}/evaluations/${evaluation.id}?shopId=${shop.id}`,{headers:headers('OWNER')});assert.equal(exported.status,200);
  const body=await exported.json() as {data:{snapshot:typeof evaluation.snapshot;choices:typeof evaluation.choices;seed:number;outcome:unknown}};
  assert.equal(replayHash(runMatchedReplay(body.data.snapshot,body.data.choices,body.data.seed)),replayHash(body.data.outcome));
  console.log('EVIDENCE_EVENT '+JSON.stringify({operation:'matched-sandbox-agent-count',expected:4,observed:evaluation.outcome.scorecards.length,success:true}));
  if (process.env.EMIT_MATCHED_EVIDENCE==='1') saveEvidence('matched-evaluation',evaluation);
});
