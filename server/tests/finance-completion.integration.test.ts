import assert from 'node:assert/strict';
import { test } from 'node:test';
import { randomUUID } from 'node:crypto';
import prisma from '../src/shared/prisma';
import { cashflowService } from '../src/app/modules/finance/cashflow/cashflow.service';
import { loadProfileAggregates } from '../src/app/modules/finance/shared/shopData';
import express, { NextFunction, Request, Response } from 'express';
import jwt from 'jsonwebtoken';
import config from '../src/config';
import { cashflowRoutes } from '../src/app/modules/finance/cashflow/cashflow.routes';
import { agentsRoutes } from '../src/app/modules/finance/agents/agents.routes';

test('cash event synchronization, expense alert and supplier evidence', { skip: process.env.FINANCE_COMPLETION_TEST_DATABASE !== '1' }, async t => {
  const url = new URL(process.env.DATABASE_URL!);
  assert.equal(url.hostname,'127.0.0.1'); assert.equal(url.pathname,'/simulator_test');
  t.after(() => prisma.$disconnect());
  const user = await prisma.user.create({ data: { number: randomUUID(), role: ['OWNER'], OTP: 0 } });
  await prisma.owner.create({ data: { userID: user.id, number: user.number, name: 'Synthetic owner', email: `${randomUUID()}@example.invalid`, dob: '1990-01-01', address: 'Synthetic' } });
  const tenant = await prisma.tenant.create({ data: { ownerID: user.id, name: 'Evidence tenant' } });
  const shop = await prisma.shop.create({ data: { tenantID: tenant.id, ownerID: user.id, shopName: 'Evidence shop', contact: 'Synthetic' } });
  const scope = { tenantID: tenant.id, shopID: shop.id };
  const balance = async () => (await prisma.cashAccount.aggregate({ where: scope, _sum: { currentBalance: true } }))._sum.currentBalance ?? 0;
  const trace = (operation: string, expected: number, observed: number) => {
    console.log('EVIDENCE_EVENT ' + JSON.stringify({ operation, expected, observed, success: expected === observed }));
  };
  await t.test('paid sale and edits update cash atomically; drafts and rollback do not', async () => {
    const sale = await prisma.checkout.create({ data: { ...scope, totalPrice: 100, totalQuantity: 1, status: 'PAID' } });
    assert.equal(await balance(),100);
    await prisma.checkout.update({ where: { id: sale.id }, data: { totalPrice: 120 } });
    assert.equal(await balance(),120);
    await prisma.checkout.delete({ where: { id: sale.id } });
    assert.equal(await balance(),0);
    trace('cash-after-paid-sale-edit-delete',0,await balance());
    await prisma.checkout.create({ data: { ...scope, totalPrice: 999, totalQuantity: 1, status: 'PAID', isDraft: true } });
    assert.equal(await balance(),0);
    await assert.rejects(prisma.$transaction(async tx => { await tx.checkout.create({ data: { ...scope, totalPrice: 400, totalQuantity: 1, status: 'PAID' } }); throw new Error('rollback'); }),/rollback/);
    assert.equal(await balance(),0);
  });
  await t.test('partial then full debt repayment is counted once, including repeated backfill', async () => {
    const buyer = await prisma.user.create({ data: { number: randomUUID(), role: ['BUYER'], OTP: 0 } });
    await prisma.buyer.create({ data: { userID: buyer.id, number: buyer.number, name: 'Synthetic buyer', address: 'Synthetic' } });
    const sale = await prisma.checkout.create({ data: { ...scope, buyerID: buyer.id, totalPrice: 100, totalQuantity: 1, status: 'UNPAID' } });
    const debt = await prisma.debt.create({ data: { ...scope, buyerID: buyer.id, checkoutID: sale.id } });
    await prisma.debtPayments.create({ data: { debtId: debt.id, amount: 30 } });
    assert.equal(await balance(),30);
    await prisma.$transaction(async tx => { await tx.debtPayments.create({ data: { debtId: debt.id, amount: 70 } }); await tx.debt.update({ where: { id: debt.id }, data: { status: 'PAID', paidAmount: 100 } }); await tx.checkout.update({ where: { id: sale.id }, data: { status: 'PAID' } }); });
    assert.equal(await balance(),100);
    await cashflowService.backfill(tenant.id,shop.id);
    await cashflowService.backfill(tenant.id,shop.id);
    assert.equal(await balance(),100);
    assert.equal(await prisma.cashTransaction.count({ where: { ...scope, category: 'SALES_COLLECTION' } }),0);
    trace('cash-after-partial-full-and-two-backfills',100,await balance());
  });
  await t.test('concurrent sales retain the correct cached balance', async () => {
    await Promise.all([1,2].map(() => prisma.checkout.create({ data: { ...scope, totalPrice: 25, totalQuantity: 1, status: 'PAID' } })));
    assert.equal(await balance(),150);
    trace('cash-after-concurrent-sales',150,await balance());
  });
  const expense = await prisma.expense.create({ data: { ...scope, month: 10, year: 2026, totalAmount: 1100 } });
  await t.test('expense spike uses historical category median; edits and deletion update cash', async () => {
    await prisma.expenseItem.create({ data: { tenantID: tenant.id, expenseID: expense.id, amount: 100, expenseType: 'GENERAL', createdAt: new Date(Date.now()-20*86400000) } });
    const item = await prisma.expenseItem.create({ data: { tenantID: tenant.id, expenseID: expense.id, amount: 1000, expenseType: 'GENERAL' } });
    assert.equal(await balance(),-950);
    const result = await cashflowService.runTreasury(tenant.id,shop.id);
    assert(JSON.stringify(result).includes('EXPENSE_SPIKE'));
    trace('expense-spike-alert-count',1,await prisma.cashAlert.count({ where: { ...scope, alertType:'EXPENSE_SPIKE' } }));
    await prisma.expenseItem.update({ where: { id: item.id }, data: { amount: 500 } });
    assert.equal(await balance(),-450);
    await prisma.expenseItem.delete({ where: { id: item.id } });
    assert.equal(await balance(),50);
    const refund = await prisma.expenseItem.create({ data: { tenantID: tenant.id, expenseID: expense.id, amount: -20, expenseType: 'GENERAL' } });
    assert.equal(await balance(),70,'a signed expense reversal increases cash');
    const fractional = await prisma.expenseItem.create({ data: { tenantID: tenant.id, expenseID: expense.id, amount: 1.005, expenseType: 'GENERAL' } });
    assert.equal(await balance(),68.99,'the cached balance uses the same rounded amount as the ledger');
    await prisma.expenseItem.deleteMany({ where: { id: { in: [refund.id,fractional.id] } } });
    assert.equal(await balance(),50);
  });
  await t.test('recorded supplier obligations affect payables and require unique purchase evidence', async () => {
    const payable = await cashflowService.createCommitment(tenant.id,shop.id,{ name: 'Supplier invoice fixture', amount: 200, dueDate: new Date(Date.now()+86400000).toISOString(), supplierPayable: true });
    assert.equal((await loadProfileAggregates(tenant.id,shop.id)).payables,200);
    trace('recorded-supplier-payables',200,(await loadProfileAggregates(tenant.id,shop.id)).payables);
    await cashflowService.createCommitment(tenant.id,shop.id,{ name: 'Future expense, not a payable', amount: 999, dueDate: new Date().toISOString() });
    assert.equal((await loadProfileAggregates(tenant.id,shop.id)).payables,200);
    const payment = await prisma.expenseItem.create({ data: { tenantID: tenant.id, expenseID: expense.id, amount: 200, expenseType: 'PRODUCT', createdAt: new Date(payable.createdAt.getTime()+10) } });
    await assert.rejects(cashflowService.settleCommitment('foreign-tenant',shop.id,payable.id,payment.id));
    const cashBefore = await balance();
    await cashflowService.settleCommitment(tenant.id,shop.id,payable.id,payment.id);
    await cashflowService.settleCommitment(tenant.id,shop.id,payable.id,payment.id);
    assert.equal(await balance(),cashBefore);
    assert.equal((await loadProfileAggregates(tenant.id,shop.id)).payables,0);
    trace('payables-after-linking-existing-purchase',0,(await loadProfileAggregates(tenant.id,shop.id)).payables);
    await assert.rejects(prisma.expenseItem.delete({ where: { id: payment.id } }),/settled supplier evidence/);
    await assert.rejects(prisma.expenseItem.update({ where: { id: payment.id }, data: { amount: 250 } }),/settled supplier evidence/);
    const duplicate = await cashflowService.createCommitment(tenant.id,shop.id,{ name: 'Other invoice', amount: 200, dueDate: new Date().toISOString(), supplierPayable: true });
    await prisma.cashCommitment.update({ where: { id: duplicate.id }, data: { createdAt: payable.createdAt } });
    await assert.rejects(cashflowService.settleCommitment(tenant.id,shop.id,duplicate.id,payment.id),/already linked/);
  });
  await t.test('comparison and supplier routes enforce authentication, validation and owner writes', async () => {
    const app = express(); app.use(express.json()); app.use('/cashflow',cashflowRoutes); app.use('/agents',agentsRoutes);
    app.use((error: { statusCode?: number; message: string },_req: Request,res: Response,_next: NextFunction) => res.status(error.statusCode ?? 400).json({ message: error.message }));
    const server = app.listen(0,'127.0.0.1');
    await new Promise<void>(resolve => server.once('listening',resolve));
    t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
    const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
    const headers = (role: string) => ({ 'Content-Type':'application/json', Authorization: `Bearer ${jwt.sign({ userID:user.id,role },config.jwt.secret!)}`, 'x-tenant-id':tenant.id });
    const response = await fetch(`${base}/agents/sandbox-comparison?shopId=${shop.id}`,{ headers:headers('OWNER') });
    assert.equal(response.status,200);
    const payload = await response.json() as { data: { cases: unknown[]; mode: string } };
    assert.equal(payload.data.mode,'fixture-policy-not-AI'); assert.equal(payload.data.cases.length,3);
    assert.equal((await fetch(`${base}/agents/sandbox-comparison?shopId=foreign`,{ headers:headers('OWNER') })).status,404);
    assert.equal((await fetch(`${base}/cashflow/commitments`,{ method:'POST',headers:headers('EMPLOYEE'),body:JSON.stringify({ shopId:shop.id,name:'Forbidden',amount:100,dueDate:'2026-10-20',supplierPayable:true }) })).status,403);
    assert.equal((await fetch(`${base}/cashflow/commitments`,{ method:'POST',headers:headers('OWNER'),body:JSON.stringify({ shopId:shop.id,name:'Invalid',amount:-1,dueDate:'not-date' }) })).status,400);
  });
});
